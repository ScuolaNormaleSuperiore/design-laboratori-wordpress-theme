<?php
/**
 * Base class of the integration tests.
 *
 * @package Design_Laboratori_Italia
 */

/**
 * Adds the Italian language to the test database and a few helpers.
 *
 * Polylang starts with no language in an empty database, so every test that
 * queries content by language needs `it` to exist. Everything runs inside the
 * transaction of the WordPress test framework and is rolled back at the end.
 */
abstract class DLI_Integration_Test_Case extends WP_UnitTestCase {

	/**
	 * Create the Italian language, the default one of the theme.
	 */
	public function set_up() {
		parent::set_up();

		$language = PLL()->model->languages->add(
			array(
				'name'   => 'Italiano',
				'slug'   => 'it',
				'locale' => 'it_IT',
				'rtl'    => false,
				'flag'   => 'it',
			)
		);
		if ( is_wp_error( $language ) ) {
			$this->fail( 'Cannot create the Italian language: ' . $language->get_error_message() );
		}
	}

	/**
	 * Option groups written with set_theme_options() during the test.
	 *
	 * @var string[]
	 */
	private $theme_option_groups = array();

	/**
	 * Empty the theme option groups used by the test and forget the languages
	 * cached in memory: the database is rolled back, the in-memory caches are not.
	 */
	public function tear_down() {
		// Inside the transaction, so that the reset is rolled back too.
		foreach ( $this->theme_option_groups as $group ) {
			cmb2_options( $group )->set( array() );
		}
		parent::tear_down();
		PLL()->model->languages->clean_cache();
	}

	/**
	 * Replace a theme option group (for example `setup`).
	 *
	 * CMB2 keeps the options it has read in memory for the whole process, so
	 * `update_option()` alone is not seen by `dli_get_option()` in later tests.
	 *
	 * @param string $group  Option group key.
	 * @param array  $values Option values.
	 */
	protected function set_theme_options( $group, array $values ) {
		$this->theme_option_groups[] = $group;
		cmb2_options( $group )->set( $values );
	}

	/**
	 * Core hooks that read files generated by the WordPress build (emoji loader, block styles).
	 *
	 * The wordpress-develop test checkout is not built, so these hooks fail while a template prints
	 * the theme header and footer. The tests that render a template only check what the template
	 * outputs: the hooks are detached while it renders and restored afterwards.
	 *
	 * @var array<int, array{0: string, 1: string}>
	 */
	const CORE_ASSET_HOOKS = array(
		array( 'wp_head', 'wp_maybe_inline_styles' ),
		array( 'wp_footer', 'wp_maybe_inline_styles' ),
		array( 'wp_footer', 'wp_print_footer_scripts' ),
	);

	/**
	 * Render a template of the theme, with its header and footer, and return the HTML.
	 *
	 * The template runs in the scope of this method: it must read the current post from the global
	 * `$post` (see render_single()), exactly as the theme templates do.
	 *
	 * @param string $relative_path Path of the template inside the theme folder.
	 * @return string Rendered HTML.
	 */
	protected function render_theme_template( $relative_path ) {
		$detached = array();

		foreach ( self::CORE_ASSET_HOOKS as list( $hook, $callback ) ) {
			$priority = has_action( $hook, $callback );
			if ( false !== $priority ) {
				remove_action( $hook, $callback, $priority );
				$detached[] = array( $hook, $callback, $priority );
			}
		}

		try {
			ob_start();
			include get_template_directory() . '/' . ltrim( $relative_path, '/' );
			return (string) ob_get_clean();
		} finally {
			foreach ( $detached as list( $hook, $callback, $priority ) ) {
				add_action( $hook, $callback, $priority );
			}
		}
	}

	/**
	 * Set the ACF fields of a post by field name.
	 *
	 * The names are resolved to field keys through the field groups registered for the post type, as
	 * ACF cannot resolve the name of a field that has no stored value yet.
	 *
	 * @param int                  $post_id Post ID.
	 * @param array<string, mixed> $fields  Values, by field name.
	 */
	protected function set_acf_fields( $post_id, array $fields ) {
		$post_type = get_post_type( $post_id );
		$keys      = array();

		foreach ( acf_get_field_groups( array( 'post_type' => $post_type ) ) as $group ) {
			foreach ( acf_get_fields( $group['key'] ) as $field ) {
				$keys[ $field['name'] ] = $field['key'];
			}
		}

		foreach ( $fields as $name => $value ) {
			$this->assertArrayHasKey( $name, $keys, "No ACF field named $name for the post type $post_type." );
			update_field( $keys[ $name ], $value, $post_id );
		}
	}

	/**
	 * Create a post of any type in the Italian language.
	 *
	 * @param string $post_type Post type.
	 * @param string $title     Title.
	 * @param string $status    Post status.
	 * @return int Post ID.
	 */
	protected function create_post( $post_type, $title, $status = 'publish' ) {
		$post_id = self::factory()->post->create(
			array(
				'post_type'   => $post_type,
				'post_title'  => $title,
				'post_status' => $status,
			)
		);
		dli_set_post_language( $post_id, 'it' );
		return $post_id;
	}
}
